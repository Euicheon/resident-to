def norm_region(s):
    s = s.strip()
    return REGION_MAP.get(s, s)

def norm_dept(s):
    s = s.strip()
    return DEPT_MAP.get(s, s)

def norm_hospital(s):
    s = s.strip()
    return HOSPITAL_ALIASES.get(s, s)

def parse_int(val):
    if val is None:
        return None
    s = str(val).strip()
    if not s or s == "-":
        return None
    try:
        return int(s)
    except ValueError:
        return None

def parse_meta(fname):
    nfc = unicodedata.normalize("NFC", fname)
    typ = "intern" if "인턴" in nfc else "resident"
    ym = re.search(r"(20\d{2})", nfc)
    year = int(ym.group(1)) if ym else 0
    if "전반기" in nfc:
        half, hs = "전반기", 1
    elif "후반기" in nfc:
        half, hs = "후반기", 2
    else:
        half, hs = "전반기", 1
    term_id = f"{year}-{hs}"
    return typ, year, half, hs, term_id

def main():
    records = []
    terms = {}
    for path in sorted(glob.glob(os.path.join(SRC, "*.csv"))):
        fname = os.path.basename(path)
        typ, year, half, hs, term_id = parse_meta(fname)
        terms[term_id] = {
            "id": term_id, "year": year, "half": half,
            "label": f"{year} {half}", "sort": year*10+hs,
        }
        with open(path, encoding="utf-8-sig") as fh:
            rows = list(csv.reader(fh))
        if not rows:
            continue
        hdr = [h.strip() for h in rows[0]]
        has_breakdown = "기본정원" in hdr
        for raw in rows[1:]:
            if not any(c.strip() for c in raw):
                continue
            d = dict(zip(hdr, raw))
            to = parse_int(d.get("TO", "0")) or 0
            raw_hosp = d.get("병원명", "").strip()
            hosp = norm_hospital(raw_hosp)
            note = (d.get("비고", "") or "").strip()
            if note == "-":
                note = ""
            rec = {
                "term": term_id,
                "type": typ,
                "region": norm_region(d.get("지역", "")),
                "hospital": hosp,
                "dept": norm_dept(d.get("과목", "")) if typ == "resident" else "",
                "to": to,
                "note": note,
            }
            if has_breakdown:
                b_raw = (d.get("기본정원", "") or "").strip()
                ex = parse_int(d.get("별도정원"))
                ct = parse_int(d.get("감원"))
                if b_raw:
                    rec["base"] = b_raw
                if ex:
                    rec["extra"] = ex
                if ct:
                    rec["cut"] = ct
            records.append(rec)

    term_list = sorted(terms.values(), key=lambda t: t["sort"])
    regions_present = {r["region"] for r in records if r["region"]}
    regions = [r for r in REGION_ORDER if r in regions_present]
    regions += sorted(regions_present - set(regions))
    depts = sorted({r["dept"] for r in records if r["dept"]})

    payload = {
        "generatedAt": datetime.datetime.now().isoformat(timespec="seconds"),
        "terms": term_list,
        "regions": regions,
        "depts": depts,
        "schools": MEDICAL_SCHOOLS,
        "records": records,
    }
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("// 자동 생성 파일 — build_data.py 로 재생성. 직접 수정 금지.\n")
        fh.write("window.RESIDENT_DATA = ")
        json.dump(payload, fh, ensure_ascii=False, separators=(",", ":"))
        fh.write(";\n")

    print(f"records={len(records)}  terms={len(term_list)}  regions={len(regions)}  depts={len(depts)}")
    for t in term_list:
        r_sum = sum(r["to"] for r in records if r["term"] == t["id"] and r["type"] == "resident")
        i_sum = sum(r["to"] for r in records if r["term"] == t["id"] and r["type"] == "intern")
        print(f"  {t['label']:10s} | 레지던트 TO: {r_sum:5d} | 인턴 TO: {i_sum:5d}")
    print(f"-> {OUT}")

if __name__ == "__main__":
    main()
